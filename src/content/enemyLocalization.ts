export function normalizeEnemyResultKey(
  value?: string | null,
): EnemyResultKey | null {
  if (!value) return null;

  const normalized = value.toLowerCase().replace(/[^a-z]/g, "");

  if (normalized === "mystan") return "mystan";
  if (normalized === "zheztyrnak") return "zheztyrnak";
  if (normalized === "aydahar" || normalized === "aidahar") return "aydahar";
  if (normalized === "zhalgyzkozdidau") return "zhalgyzKozdiDau";

  return null;
}

export function getEnemyLocalization(language: string) {
  return ENEMY_LOCALIZATION[language as EnemyLocalizationLanguage] ?? null;
}

export function getEnemyResultImageByKey(value?: string | null) {
  const key = normalizeEnemyResultKey(value);
  return key ? ENEMY_RESULT_IMAGE_MAP[key] : null;
}

