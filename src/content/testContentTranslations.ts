function normalizeLanguage(language: string): ContentLanguage {
  if (language.startsWith("ru")) return "ru";
  if (language.startsWith("kk")) return "kk";
  return "en";
}

function getLocalizedTestTranslation(language: string, type: string) {
  const normalized = normalizeLanguage(language);
  if (normalized === "en") return null;
  return TEST_TRANSLATIONS[normalized]?.[type as TestType] ?? null;
}

function translateBigFiveNarrative(language: SupportedLocalizedLanguage, narrative?: string) {
  if (!narrative) return narrative;
  return BIG_FIVE_NARRATIVES[language][narrative] ?? narrative;
}

function localizeDevelopmentFocus(language: SupportedLocalizedLanguage, value?: string | null) {
  if (!value) return value;
  return DEVELOPMENT_FOCUS[language][value] ?? value;
}

function buildPersonalityWhy(
  language: SupportedLocalizedLanguage,
  title: string,
  topTraits: string[],
  firstNarrative?: string,
) {
  const [first, second] = topTraits;
  if (!first || !second) return null;

  if (language === "ru") {
    return `${title} подходит вам лучше всего, потому что ваш профиль сильнее всего тяготеет к ${first.toLowerCase()} и ${second.toLowerCase()}. ${firstNarrative ?? ""}`.trim();
  }

  return `${title} сізге көбірек сай келеді, себебі профиліңіз ең алдымен ${first.toLowerCase()} пен ${second.toLowerCase()} бағытына жақын. ${firstNarrative ?? ""}`.trim();
}

function buildAnimalWhy(
  language: SupportedLocalizedLanguage,
  title: string,
  temperament: string,
  extraversionLabel?: string,
  stabilityLabel?: string,
  narratives?: string[],
) {
  const [firstNarrative, secondNarrative] = narratives ?? [];
  if (language === "ru") {
    return `${title} подходит вам лучше всего, потому что ваши ответы тяготели к ${extraversionLabel?.toLowerCase() ?? ""} и ${stabilityLabel?.toLowerCase() ?? ""}. В двухосевой модели Айзенка это соответствует темпераменту ${temperament.toLowerCase()}. ${firstNarrative ?? ""} ${secondNarrative ?? ""}`.trim();
  }

  return `${title} сізге көбірек сай келеді, себебі жауаптарыңыз ${extraversionLabel?.toLowerCase() ?? ""} пен ${stabilityLabel?.toLowerCase() ?? ""} жағына бейім болды. Айзенктің екі өс моделінде бұл ${temperament.toLowerCase()} темпераментіне сәйкес келеді. ${firstNarrative ?? ""} ${secondNarrative ?? ""}`.trim();
}

function translateScaleOption(language: SupportedLocalizedLanguage, option: any) {
  if (!option?.id) return option;
  const label = SHARED_SCALE_OPTIONS[language][option.id];
  if (!label) return option;
  return { ...option, label };
}

export function localizeTestType(type: string, language: string) {
  const normalized = normalizeLanguage(language);
  if (type === "enemy") {
    if (normalized === "ru") return "Враг";
    if (normalized === "kk") return "Жау";
  }
  return TYPE_LABELS[normalized][type] ?? type;
}

export function localizeTestSummary<T extends { type: string; title: string; description: string; image_alt?: string; info_boxes?: any[] }>(
  test: T,
  language: string,
): T {
  const normalized = normalizeLanguage(language);
  const enemyLocalization =
    test.type === "enemy" ? getEnemyLocalization(normalized) : null;
  const translation = getLocalizedTestTranslation(language, test.type);
  if (!translation && !enemyLocalization) return test;

  const infoBoxesSource = translation?.infoBoxes ?? enemyLocalization?.infoBoxes;

  return {
    ...test,
    title: translation?.title ?? enemyLocalization?.title ?? test.title,
    description:
      translation?.description ?? enemyLocalization?.description ?? test.description,
    image_alt: translation?.imageAlt ?? enemyLocalization?.imageAlt ?? test.image_alt,
    info_boxes: test.info_boxes?.map((box: any) => {
      const localizedBox = infoBoxesSource?.[box.tone as InfoTone];
      return localizedBox ? { ...box, ...localizedBox } : box;
    }),
  };
}

export function localizeTestDetail<
  T extends {
    type: string;
    title: string;
    description: string;
    image_alt?: string;
    info_boxes?: any[];
    questions?: Array<{ order: number; title: string; prompt?: string | null; options?: any[] | null }>;
  },
>(test: T, language: string): T {
  const normalized = normalizeLanguage(language);
  const translation = getLocalizedTestTranslation(language, test.type);
  if (normalized === "en") return test;

  if (!translation) {
    return localizeTestSummary(test, language);
  }

  return {
    ...localizeTestSummary(test, language),
    questions: test.questions?.map((question) => {
      const localizedQuestion = translation.questions[question.order];
      if (!localizedQuestion) return question;

      const options =
        question.options?.map((option: any) => {
          if (test.type === "personality" || test.type === "animal") {
            return translateScaleOption(normalized, option);
          }

          const localizedLabel = localizedQuestion.options?.[option.id];
          return localizedLabel ? { ...option, label: localizedLabel } : option;
        }) ?? question.options;

      return {
        ...question,
        title: localizedQuestion.title,
        prompt: localizedQuestion.prompt ?? question.prompt,
        options,
      };
    }),
  };
}

export function localizeResultPayload<T extends { resultKey?: string; title?: string; subtitle?: string | null; tagline?: string; description?: string; strengths?: string[]; growthAreas?: string[]; developmentFocus?: string | null; whyThisResult?: string | null; imageSrc?: string; image_src?: string; imageAlt?: string; image_alt?: string; details?: any }>(
  testType: string,
  result: T,
  language: string,
): T {
  const normalized = normalizeLanguage(language);
  if (normalized === "en") return result;

  const enemyLocalization =
    testType === "enemy" ? getEnemyLocalization(normalized) : null;
  const enemyKey =
    testType === "enemy" ? normalizeEnemyResultKey(result.resultKey) : null;
  const enemyResultTranslation =
    enemyLocalization && enemyKey ? enemyLocalization.results[enemyKey] : null;
  const enemyImage = getEnemyResultImageByKey(result.resultKey);
  const translation = getLocalizedTestTranslation(language, testType)?.results?.[result.resultKey ?? ""];
  if (!translation && !enemyResultTranslation && !enemyImage) return result;

  const localized: T = {
    ...result,
    title:
      enemyResultTranslation?.title ??
      translation?.title ??
      result.title,
    subtitle:
      enemyResultTranslation?.subtitle ??
      translation?.subtitle ??
      result.subtitle,
    tagline:
      enemyResultTranslation?.tagline ??
      translation?.tagline ??
      result.tagline,
    description:
      enemyResultTranslation?.description ??
      translation?.description ??
      result.description,
    strengths:
      enemyResultTranslation?.strengths ??
      translation?.strengths ??
      result.strengths,
    growthAreas:
      enemyResultTranslation?.growthAreas ??
      translation?.growthAreas ??
      result.growthAreas,
    developmentFocus:
      translation?.developmentFocus ??
      localizeDevelopmentFocus(normalized, result.developmentFocus),
    whyThisResult: translation?.whyThisResult ?? result.whyThisResult,
    imageSrc: enemyImage?.imageSrc ?? result.imageSrc,
    image_src: enemyImage?.imageSrc ?? result.image_src,
    imageAlt: enemyImage?.imageAlt ?? result.imageAlt,
    image_alt: enemyImage?.imageAlt ?? result.image_alt,
  };

  if (localized.details) {
    const details = { ...localized.details };

    if (typeof details.shadowArchetype === "string") {
      details.shadowArchetype =
        translation?.shadowArchetype ??
        RESULT_TITLE_LOOKUP[normalized][details.shadowArchetype] ??
        details.shadowArchetype;
    }

    if (Array.isArray(details.topTraits)) {
      details.topTraits = details.topTraits.map((trait: string) => {
        const key = Object.entries(BIG_FIVE_TRAITS[normalized]).find(
          ([, value]) => value.label === trait,
        )?.[0];
        if (key) return BIG_FIVE_TRAITS[normalized][key].label;

        const byEnglishKey = Object.entries(BIG_FIVE_TRAITS[normalized]).find(
          ([englishKey, value]) =>
            englishKey.toLowerCase() === trait.toLowerCase() || value.label === trait,
        )?.[0];
        return byEnglishKey
          ? BIG_FIVE_TRAITS[normalized][byEnglishKey].label
          : RESULT_TITLE_LOOKUP[normalized][trait] ?? trait;
      });
    }

    if (Array.isArray(details.coreTraits) && translation?.coreTraits) {
      details.coreTraits = translation.coreTraits;
    }

    if (translation?.temperament) {
      details.temperament = translation.temperament;
    }

    if (translation?.quadrant) {
      details.quadrant = translation.quadrant;
    }

    if (Array.isArray(details.bigFive)) {
      details.bigFive = details.bigFive.map((trait: any) => {
        const traitTranslation = BIG_FIVE_TRAITS[normalized][trait.key];
        return {
          ...trait,
          label: traitTranslation?.label ?? trait.label,
          description: traitTranslation?.description ?? trait.description,
          narrative: translateBigFiveNarrative(normalized, trait.narrative),
        };
      });
    }

    if (Array.isArray(details.axes)) {
      details.axes = details.axes.map((axis: any) => {
        const fields = ANIMAL_AXIS_FIELDS[normalized][axis.key];
        const highPole = fields?.highPole ?? axis.highPole;
        const lowPole = fields?.lowPole ?? axis.lowPole;
        return {
          ...axis,
          label: fields?.label ?? axis.label,
          highPole,
          lowPole,
          leaningLabel: axis.score >= 50 ? highPole : lowPole,
          narrative: translateBigFiveNarrative(normalized, axis.narrative),
        };
      });
    }

    if (enemyResultTranslation) {
      if (typeof details.threatenedNeed === "string") {
        details.threatenedNeed = enemyResultTranslation.threatenedNeed;
      }

      if (typeof details.needDescription === "string") {
        details.needDescription = enemyResultTranslation.needDescription;
      }

      if (typeof details.psychologicalBasis === "string") {
        details.psychologicalBasis = enemyResultTranslation.psychologicalBasis;
      }

      if (typeof details.howItWins === "string") {
        details.howItWins = enemyResultTranslation.howItWins;
      }

      if (typeof details.hiddenTraitSummary === "string") {
        details.hiddenTraitSummary = enemyResultTranslation.hiddenTraitSummary;
      }

      if (typeof details.warningSign === "string") {
        details.warningSign = enemyResultTranslation.warningSign;
      }

      if (typeof details.resistance === "string") {
        details.resistance = enemyResultTranslation.resistance;
      }

      if (Array.isArray(details.distortionPatterns)) {
        details.distortionPatterns = enemyResultTranslation.distortionPatterns;
      }

      if (Array.isArray(details.enemyScores)) {
        details.enemyScores = details.enemyScores.map((score: any) => {
          const scoreKey = normalizeEnemyResultKey(score.key);
          const scoreTranslation =
            scoreKey && enemyLocalization
              ? enemyLocalization.results[scoreKey]
              : null;

          return {
            ...score,
            title: scoreTranslation?.title ?? score.title,
            label: scoreTranslation?.title ?? score.label,
            narrative:
              scoreTranslation?.scoreNarrative ?? score.narrative,
          };
        });
      }
    }

    localized.details = details;
  }

  if (testType === "personality" && localized.details?.topTraits) {
    const firstNarrative = localized.details?.bigFive?.find(
      (trait: any) => trait.label === localized.details.topTraits[0],
    )?.narrative;
    localized.whyThisResult = buildPersonalityWhy(
      normalized,
      localized.title ?? result.title ?? "",
      localized.details.topTraits,
      firstNarrative,
    );
  }

  if (testType === "animal" && localized.details?.axes) {
    const extraversionAxis = localized.details.axes.find(
      (axis: any) => axis.key === "extraversion",
    );
    const stabilityAxis = localized.details.axes.find(
      (axis: any) => axis.key === "stability",
    );
    localized.whyThisResult = buildAnimalWhy(
      normalized,
      localized.title ?? result.title ?? "",
      localized.details.temperament ?? "",
      extraversionAxis?.leaningLabel,
      stabilityAxis?.leaningLabel,
      [extraversionAxis?.narrative, stabilityAxis?.narrative],
    );
  }

  return localized;
}

export function localizeSubmission<
  T extends {
    test_type: string;
    test_title: string;
    result: any;
  },
>(submission: T, language: string): T {
  return {
    ...submission,
    test_title: localizeTestSummary(
      {
        type: submission.test_type,
        title: submission.test_title,
        description: "",
      },
      language,
    ).title,
    result: localizeResultPayload(submission.test_type, submission.result, language),
  };
}

export function localizeCommunityResult<
  T extends {
    test_type: string;
    test_title: string;
    title: string;
    subtitle?: string | null;
    description?: string;
    image_src?: string;
    image_alt?: string;
    result_key: string;
  },
>(result: T, language: string): T {
  const translatedResult = localizeResultPayload(
    result.test_type,
    {
      resultKey: result.result_key,
      title: result.title,
      subtitle: result.subtitle,
      description: result.description,
      image_src: result.image_src,
      image_alt: result.image_alt,
    },
    language,
  );

  return {
    ...result,
    test_title: localizeTestSummary(
      { type: result.test_type, title: result.test_title, description: "" },
      language,
    ).title,
    title: translatedResult.title ?? result.title,
    subtitle: translatedResult.subtitle ?? result.subtitle,
    description: translatedResult.description ?? result.description,
    image_src: translatedResult.image_src ?? result.image_src,
    image_alt: translatedResult.image_alt ?? result.image_alt,
  };
}
